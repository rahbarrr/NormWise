export const getHistoryStatistics = (records = MOCK_HISTORY_RECORDS) => {
  const activeRecords = records.filter((r) => !r.archived);
  return {
    total: activeRecords.length,
    accepted: activeRecords.filter((r) => r.status === "Accepted").length,
    underReview: activeRecords.filter((r) => r.status === "Under Technical Review").length,
    clarificationRequested: activeRecords.filter(
      (r) => r.status === "Clarification Requested"
    ).length,
  };
};
